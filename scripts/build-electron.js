#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const PROFILES = {
  mws: {
    url: 'https://mws.digitalclub.com.pe',
    productName: 'MWS Desktop',
    appId: 'com.contactototal.mws-desktop',
    output: 'release/mws',
    artifactName: 'MWS-Desktop.${ext}',
    shortcutName: 'MWS Desktop'
  },
  infinance: {
    url: 'https://infinance.innovag.com.pe',
    productName: 'InFinance Desktop',
    appId: 'com.innovag.infinance-desktop',
    output: 'release/infinance',
    artifactName: 'InFinance-Desktop.${ext}',
    shortcutName: 'InFinance Desktop'
  }
};

const arg = process.argv[2];
let profile;

if (arg && PROFILES[arg]) {
  profile = arg;
} else if (arg && arg.startsWith('http')) {
  // Backward compatibility: a URL was passed instead of a profile name
  if (arg.includes('mws.digitalclub.com.pe')) {
    profile = 'mws';
  } else if (arg.includes('infinance.innovag.com.pe')) {
    profile = 'infinance';
  } else {
    console.error('[build-electron] Unknown URL: ' + arg);
    console.error('  Known profiles: ' + Object.keys(PROFILES).join(', '));
    process.exit(1);
  }
} else {
  console.error('Usage: node scripts/build-electron.js <profile>');
  console.error('  Profiles: ' + Object.keys(PROFILES).join(', '));
  process.exit(1);
}

const cfg = PROFILES[profile];
const angularUrl = cfg.url.endsWith('/') ? cfg.url : cfg.url + '/';

// 1) Write electron/app-config.ts (consumed by main.ts and update-checker.ts)
const appConfig =
  `// Auto-generated by scripts/build-electron.js — do not edit manually\n` +
  `// To regenerate: node scripts/build-electron.js <profile>\n` +
  `// Active profile: ${profile}\n` +
  `export const PROFILE = '${profile}';\n` +
  `export const PRODUCT_NAME = '${cfg.productName}';\n` +
  `export const APP_ID = '${cfg.appId}';\n` +
  `export const DEFAULT_BACKEND_URL = process.env.BACKEND_URL || '${cfg.url}';\n` +
  `export const DEFAULT_ANGULAR_URL = process.env.ANGULAR_URL || '${angularUrl}';\n`;
const appConfigPath = path.join(__dirname, '..', 'electron', 'app-config.ts');
fs.writeFileSync(appConfigPath, appConfig, 'utf8');

// 2) Write electron-builder.<profile>.json (passed via --config to electron-builder)
const builderConfig = {
  appId: cfg.appId,
  productName: cfg.productName,
  directories: { output: cfg.output },
  files: ['dist/**/*', 'node_modules/**/*', 'package.json'],
  artifactName: cfg.artifactName,
  win: {
    icon: 'build/icon.ico',
    target: [{ target: 'nsis', arch: ['x64'] }],
    signAndEditExecutable: false
  },
  nsis: {
    oneClick: false,
    allowToChangeInstallationDirectory: false,
    createDesktopShortcut: true,
    createStartMenuShortcut: true,
    shortcutName: cfg.shortcutName,
    runAfterFinish: true,
    installerIcon: 'build/icon.ico',
    uninstallerIcon: 'build/icon.ico',
    installerSidebar: 'build/installerSidebar.bmp',
    uninstallerSidebar: 'build/uninstallerSidebar.bmp',
    installerHeader: 'build/installerHeader.bmp'
  }
};
const builderPath = path.join(__dirname, '..', 'electron-builder.' + profile + '.json');
fs.writeFileSync(builderPath, JSON.stringify(builderConfig, null, 2) + '\n', 'utf8');

console.log('[build-electron] Profile: ' + profile);
console.log('[build-electron]   URL:         ' + cfg.url);
console.log('[build-electron]   ProductName: ' + cfg.productName);
console.log('[build-electron]   AppId:       ' + cfg.appId);
console.log('[build-electron]   Output:      ' + cfg.output);
console.log('[build-electron] Wrote: electron/app-config.ts, electron-builder.' + profile + '.json');
