#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const domain = process.argv[2];

if (!domain || !domain.startsWith('http')) {
  console.error('Usage: node scripts/build-electron.js <https://domain.com>');
  console.error('  Example: node scripts/build-electron.js https://infinance.innovag.com.pe');
  process.exit(1);
}

const angularUrl = domain.endsWith('/') ? domain : domain + '/';

const config = `// Auto-generated by scripts/build-electron.js — do not edit manually
// To regenerate: node scripts/build-electron.js <https://domain.com>
export const DEFAULT_BACKEND_URL = process.env.BACKEND_URL || '${domain}';
export const DEFAULT_ANGULAR_URL = process.env.ANGULAR_URL || '${angularUrl}';
`;

const outPath = path.join(__dirname, '..', 'electron', 'app-config.ts');
fs.writeFileSync(outPath, config, 'utf8');
console.log(`[build-electron] app-config.ts written for domain: ${domain}`);
